import type { ContentRuleId } from '../../src/core/strings/contentRules.ts';

/**
 * The Fluent Emoji the app bundles, by category. `tools/importEmoji.ts` reads this list.
 *
 * Each entry is `[upstream folder, spoken name, id?, allow?]`. `allow` lists content rules the name
 * breaks honestly, such as the star shape. The id
 * defaults to the kebab-case spoken name and becomes the file name, `assets/emoji/<id>.svg`. People
 * use the upstream "Default" tone, which is not a human skin color.
 *
 * Left out on purpose: flags, alcohol, weapons, tobacco, religious buildings and symbols, scary
 * or gross pictures, and reward symbols such as trophies and medals (hard rule 4). Timers and
 * hourglasses are left out because they read as countdown clocks.
 *
 * To add an emoji: add a line here, run `node tools/importEmoji.ts`, then `npm run voice:generate`.
 */

export type EmojiEntry = readonly [
  folder: string,
  name: string,
  id?: string,
  allow?: readonly ContentRuleId[],
  speech?: string,
];

