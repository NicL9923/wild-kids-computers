import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { cutAfterLead, DEFAULT_LEAD_CUT, DEFAULT_PROCESS_OPTIONS, processSpeech } from './audioProcessing.ts';
import { encodeOpus } from './encode.ts';
import { loadKokoro } from './kokoro.ts';
import { CLIP_DIR, SPOKEN_LIST_PATH, spokenListSchema, type SpokenList } from './spokenList.ts';

/**
 * `npm run voice:generate`. Reads the spoken string list that the Vitest task just wrote and
 * creates every clip that does not exist yet. It never touches an existing clip, so a run after a
 * small change generates only the new strings. `--prune` also deletes clips no string uses.
 */

function readSpokenList(): SpokenList {
  if (!existsSync(SPOKEN_LIST_PATH)) {
    throw new Error(`${SPOKEN_LIST_PATH} is missing. Run npm run voice:generate from the repository root.`);
  }
  return spokenListSchema.parse(JSON.parse(readFileSync(SPOKEN_LIST_PATH, 'utf8')));
}

/** The license entry for generated clips. The clips are this project's own output, so MIT. */
function writeLicenseEntry(list: SpokenList): void {
  const manifest = path.join(CLIP_DIR, 'LICENSES.json');
  if (existsSync(manifest)) return;
  const { model, voice } = list.profile;
  const entry = {
    files: '*.ogg',
    source: `Generated by tools/voice/generate.ts with ${model} (Apache-2.0 model), voice ${voice}`,
    author: 'Wild Flowers Tech',
    license: 'MIT',
  };
  writeFileSync(manifest, `${JSON.stringify([entry], null, 2)}\n`);
}

async function main(): Promise<void> {
  const list = readSpokenList();
  mkdirSync(CLIP_DIR, { recursive: true });
  writeLicenseEntry(list);
  const present = new Set(readdirSync(CLIP_DIR));
  const missing = list.clips.filter((clip) => !present.has(clip.clip));

  if (process.argv.includes('--prune')) {
    const wanted = new Set(list.clips.map((clip) => clip.clip));
    for (const file of present) {
      if (file.endsWith('.ogg') && !wanted.has(file)) {
        rmSync(path.join(CLIP_DIR, file));
        console.log(`Deleted stale clip ${file}`);
      }
    }
  }

  console.log(`${String(list.clips.length)} spoken clips, ${String(missing.length)} to generate.`);
  if (missing.length === 0) return;

  const synthesizer = await loadKokoro(list.profile);
  let done = 0;
  const failed: string[] = [];
  for (const clip of missing) {
    const { samples, sampleRate } = await synthesizer.synthesize(clip.speech);
    const spoken = cutLead(samples, sampleRate);
    if (spoken === undefined) {
      // One speech with no clear pause after the lead-in must not stop the other clips.
      failed.push(clip.speech);
      console.log(`No clip for "${clip.speech}": no pause after the lead-in.`);
      continue;
    }
    const processed = processSpeech(spoken, { ...DEFAULT_PROCESS_OPTIONS, sampleRate });
    // Write next to the target and rename, so an interrupted run leaves no half-written clip.
    const target = path.join(CLIP_DIR, clip.clip);
    const partial = `${target}.partial.ogg`;
    await encodeOpus(processed, sampleRate, partial);
    renameSync(partial, target);
    done += 1;
    console.log(`[${String(done)}/${String(missing.length)}] ${clip.clip} "${clip.speech}"`);
  }
  if (failed.length > 0) {
    console.log(`${String(failed.length)} clips were not generated. Reword the speech or add a speech override:`);
    for (const speech of failed) console.log(`  "${speech}"`);
    process.exitCode = 1;
  }
}

/**
 * Cuts the lead-in. Some sentences run the lead-in closer to the first word than the default
 * 120 ms pause, so shorter pauses are tried before giving up. The pause must still start inside
 * the lead-in window, so a pause later in the sentence is never taken for it.
 */
function cutLead(samples: Float32Array, sampleRate: number): Float32Array | undefined {
  for (const minPauseMs of [DEFAULT_LEAD_CUT.minPauseMs, 80, 50, 30]) {
    try {
      return cutAfterLead(samples, { ...DEFAULT_LEAD_CUT, sampleRate, minPauseMs });
    } catch {
      // Try the next, shorter pause.
    }
  }
  return undefined;
}

await main();
