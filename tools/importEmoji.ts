import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { EMOJI_SELECTION, type EmojiEntry } from './emoji/selection.ts';

/**
 * Copies the curated Fluent Emoji "Color" SVGs from a local clone into assets/emoji/, optimizes
 * each one when that changes no visible pixel, keeps the upstream MIT notice, writes the license
 * entry, and generates the typed list of ids and spoken names.
 *
 *   node tools/importEmoji.ts [path to fluentui-emoji clone]
 *
 * The clone defaults to ~/.cache/wkc/fluentui-emoji. This tool never fetches anything.
 * It needs `npm ci --prefix tools/emoji` once for the optimizer and the renderer.
 */

const REPO_ROOT = path.resolve(import.meta.dirname, '..');
const OUT_DIR = path.join(REPO_ROOT, 'assets', 'emoji');
const STRINGS_FILE = path.join(REPO_ROOT, 'src', 'core', 'strings', 'shared', 'emoji.ts');
const UPSTREAM_URL = 'https://github.com/microsoft/fluentui-emoji';

export interface ResolvedEmoji {
  readonly id: string;
  readonly name: string;
  readonly category: string;
  readonly folder: string;
  readonly allow: readonly string[];
  readonly speech?: string;
}

const ID_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** The default id: the spoken name in kebab-case, with accents removed. */
export function emojiIdFor(name: string): string {
  return name
    .normalize('NFD')
    .replaceAll(/\p{M}/gu, '')
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, '-')
    .replaceAll(/^-|-$/g, '');
}

/** Flattens the selection and rejects a bad id, a duplicate id, or a folder used twice. */
export function resolveSelection(selection: Readonly<Record<string, readonly EmojiEntry[]>>): ResolvedEmoji[] {
  const resolved: ResolvedEmoji[] = [];
  const ids = new Map<string, string>();
  const folders = new Map<string, string>();
  for (const [category, entries] of Object.entries(selection)) {
    for (const [folder, name, explicitId, allow, speech] of entries) {
      const id = explicitId ?? emojiIdFor(name);
      if (!ID_PATTERN.test(id)) throw new Error(`Emoji id "${id}" for ${folder} is not kebab-case.`);
      const idOwner = ids.get(id);
      if (idOwner !== undefined) throw new Error(`Emoji id "${id}" is used by ${idOwner} and ${folder}.`);
      const folderOwner = folders.get(folder);
      if (folderOwner !== undefined)
        throw new Error(`Upstream folder "${folder}" is listed as ${folderOwner} and ${id}.`);
      ids.set(id, folder);
      folders.set(folder, id);
      resolved.push({
        id,
        name,
        category,
        folder,
        allow: allow ?? [],
        ...(speech === undefined ? {} : { speech }),
      });
    }
  }
  return resolved;
}

/** The upstream Color SVG for a folder. People use the "Default" tone. */
export function colorSvgPath(cloneAssets: string, folder: string): string {
  for (const dir of [path.join(cloneAssets, folder, 'Color'), path.join(cloneAssets, folder, 'Default', 'Color')]) {
    if (!existsSync(dir)) continue;
    const svgs = readdirSync(dir).filter((file) => file.endsWith('.svg'));
    const [only] = svgs;
    if (svgs.length === 1 && only !== undefined) return path.join(dir, only);
  }
  throw new Error(`No single Color SVG for "${folder}" in ${cloneAssets}.`);
}

/** The TypeScript source of the generated emoji strings file. */
export function emojiStringsSource(emoji: readonly ResolvedEmoji[]): string {
  const lines = emoji.map(({ id, name, allow, speech }) => {
    const speechPart = speech === undefined ? '' : `, speech: ${JSON.stringify(speech)}`;
    const allowPart = allow.length > 0 ? `, allow: [${allow.map((rule) => `'${rule}'`).join(', ')}]` : '';
    return `  '${id}': { text: ${JSON.stringify(name)}${speechPart}${allowPart} },`;
  });
  const categories = [...new Set(emoji.map((entry) => entry.category))];
  const categoryLines = categories.map((category) => {
    const ids = emoji.filter((entry) => entry.category === category).map((entry) => `'${entry.id}'`);
    return `  ${category}: [${ids.join(', ')}],`;
  });
  return [
    '// Generated by tools/importEmoji.ts from tools/emoji/selection.ts. Do not edit by hand.',
    "import { defineStrings } from '../defineStrings.ts';",
    '',
    '/** The spoken name of every bundled emoji, so an activity can say what a picture shows. */',
    "export const strings = defineStrings('emoji', {",
    ...lines,
    '});',
    '',
    '/** The id of a bundled emoji. The file is `assets/emoji/<id>.svg`. */',
    'export type EmojiId = keyof typeof strings;',
    '',
    '/** Emoji ids by category, in a stable order for pickers and stamp libraries. */',
    'export const EMOJI_CATEGORIES = {',
    ...categoryLines,
    '} as const satisfies Readonly<Record<string, readonly EmojiId[]>>;',
    '',
    'export type EmojiCategory = keyof typeof EMOJI_CATEGORIES;',
    '',
  ].join('\n');
}

const kb = (bytes: number) => `${(bytes / 1024).toFixed(0)} KB`;

interface Optimizer {
  optimize(svg: string): string;
  /** RGBA pixels at a fixed size. */
  render(svg: string, size: number): Uint8Array;
}

interface SvgoModule {
  optimize: (svg: string, config: object) => { data: string };
}

interface ResvgModule {
  Resvg: new (svg: string, options: object) => { render: () => { pixels: Uint8Array } };
}

function isSvgo(value: unknown): value is SvgoModule {
  return typeof value === 'object' && value !== null && 'optimize' in value && typeof value.optimize === 'function';
}

function isResvg(value: unknown): value is ResvgModule {
  return typeof value === 'object' && value !== null && 'Resvg' in value && typeof value.Resvg === 'function';
}

function loadOptimizer(): Optimizer {
  const require = createRequire(path.join(REPO_ROOT, 'tools', 'emoji', 'package.json'));
  let svgo: unknown;
  let resvg: unknown;
  try {
    svgo = require('svgo');
    resvg = require('@resvg/resvg-js');
  } catch {
    throw new Error('Run `npm ci --prefix tools/emoji` first. It installs the SVG optimizer and renderer.');
  }
  if (!isSvgo(svgo) || !isResvg(resvg)) throw new Error('tools/emoji has an svgo or resvg with an unexpected API.');
  const { optimize } = svgo;
  const { Resvg } = resvg;
  return {
    optimize: (svg) => optimize(svg, { multipass: true }).data,
    render: (svg, size) => new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().pixels,
  };
}

export interface PixelDifference {
  /** Mean absolute difference over every channel, 0 to 255. */
  readonly mean: number;
  /** The share of channel values that moved by more than 24 of 255, 0 to 1. */
  readonly visibleShare: number;
}

/** Compares two RGBA renders of the same size. Different sizes count as entirely different. */
export function pixelDifference(a: Uint8Array, b: Uint8Array): PixelDifference {
  if (a.length !== b.length || a.length === 0) return { mean: 255, visibleShare: 1 };
  let sum = 0;
  let visible = 0;
  for (let index = 0; index < a.length; index += 1) {
    const difference = Math.abs((a[index] ?? 0) - (b[index] ?? 0));
    sum += difference;
    if (difference > 24) visible += 1;
  }
  return { mean: sum / a.length, visibleShare: visible / a.length };
}

/**
 * The optimized file is used only when its render at 256 px matches the original: anti-aliased
 * edges may shift by a pixel, nothing else may change. Measured on the curated set, the default
 * SVGO preset stays under a mean of 0.25 and a visible share of 0.3 percent.
 */
export function looksTheSame(difference: PixelDifference): boolean {
  return difference.mean <= 0.5 && difference.visibleShare <= 0.005;
}

function main(): void {
  const clone = process.argv[2] ?? path.join(os.homedir(), '.cache', 'wkc', 'fluentui-emoji');
  const assets = path.join(clone, 'assets');
  if (!existsSync(assets)) throw new Error(`No Fluent Emoji clone at ${clone}.`);
  const commit = execFileSync('git', ['-C', clone, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const emoji = resolveSelection(EMOJI_SELECTION);
  const optimizer = loadOptimizer();

  mkdirSync(OUT_DIR, { recursive: true });
  const wanted = new Set(emoji.map((entry) => `${entry.id}.svg`));
  for (const file of readdirSync(OUT_DIR)) {
    if (file.endsWith('.svg') && !wanted.has(file)) rmSync(path.join(OUT_DIR, file));
  }

  let before = 0;
  let after = 0;
  const kept: string[] = [];
  const worst: Array<PixelDifference & { id: string }> = [];
  for (const entry of emoji) {
    const original = readFileSync(colorSvgPath(assets, entry.folder), 'utf8');
    const optimized = optimizer.optimize(original);
    const difference = pixelDifference(optimizer.render(original, 256), optimizer.render(optimized, 256));
    const chosen = looksTheSame(difference) && optimized.length < original.length ? optimized : original;
    if (chosen === original) kept.push(`${entry.id} (mean ${difference.mean.toFixed(2)})`);
    worst.push({ id: entry.id, ...difference });
    writeFileSync(path.join(OUT_DIR, `${entry.id}.svg`), chosen);
    before += Buffer.byteLength(original);
    after += Buffer.byteLength(chosen);
  }

  writeFileSync(path.join(OUT_DIR, 'LICENSE'), readFileSync(path.join(clone, 'LICENSE'), 'utf8'));
  const source = `${UPSTREAM_URL} at commit ${commit}, the "Color" style`;
  const licenses = [
    { files: '*.svg', source, author: 'Microsoft Corporation', license: 'MIT' },
    {
      files: 'LICENSE',
      source: `${UPSTREAM_URL} at commit ${commit}`,
      author: 'Microsoft Corporation',
      license: 'MIT',
    },
  ];
  writeFileSync(path.join(OUT_DIR, 'LICENSES.json'), `${JSON.stringify(licenses, null, 2)}\n`);
  writeFileSync(STRINGS_FILE, emojiStringsSource(emoji));

  console.log(`Imported ${String(emoji.length)} emoji: ${kb(before)} upstream, ${kb(after)} after optimizing.`);
  if (kept.length > 0) console.log(`Kept the original for ${String(kept.length)}: ${kept.join(', ')}`);
  const top = worst.toSorted((a, b) => b.visibleShare - a.visibleShare).slice(0, 5);
  console.log(`Largest visible changes: ${top.map((d) => `${d.id} ${(d.visibleShare * 100).toFixed(2)}%`).join(', ')}`);
}

if (import.meta.main) main();
